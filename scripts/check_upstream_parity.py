"""Compare this package with the official BFL reference code at a pinned checkout.

    python scripts/check_upstream_parity.py PATH/TO/flux-3-image-klein [--expect-commit SHA]

1. fixtures/upstream_to_canvas.json is regenerated by the checkout's ``flux3.bbox.to_canvas`` and must match the
   stored copy (the stored rows were produced the same way).
2. Every row table this package composes must be recognised by the checkout's own ``flux3.bbox.detect`` /
   ``is_finished`` (the parser the official pipeline uses on prompts) and must come back unchanged.
"""

import argparse
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from flux3_layoutkit import contract as c  # noqa: E402


def load_bbox(checkout: Path):
    spec = importlib.util.spec_from_file_location("flux3_bbox_upstream", checkout / "src" / "flux3" / "bbox.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("checkout", type=Path)
    ap.add_argument("--expect-commit")
    args = ap.parse_args()
    if args.expect_commit:
        head = subprocess.run(["git", "-C", str(args.checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        if head != args.expect_commit:
            print(f"upstream checkout is {head}, expected {args.expect_commit}")
            return 1
    up = load_bbox(args.checkout)
    cases = json.loads((ROOT / "tests" / "fixtures" / "upstream_to_canvas.json").read_text(encoding="utf-8"))
    bad = 0
    for i, case in enumerate(cases):
        official = up.to_canvas(case["input"])
        if official != case["canvas_rows"]:
            print(f"case {i} ({case['source']}): stored rows differ from the checkout's to_canvas")
            bad += 1
        rows = case["canvas_rows"]
        text = c.compose_prompt(" ".join(f"<{r['id']}>" for r in rows) + " a scene", rows)
        found = up.detect(text)
        if found is None or found[1] != rows:
            print(f"case {i}: official detect() does not return the rows we composed")
            bad += 1
        elif not up.is_finished(text):
            print(f"case {i}: official is_finished() rejects the composed prompt")
            bad += 1
        for r in rows:  # the upsampler-side validator must accept each row as a well-formed addition
            if up.valid_added(r, text) is None:
                print(f"case {i}: valid_added rejects row {r['id']}")
                bad += 1
    print(f"{len(cases)} cases, {bad} problems")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
